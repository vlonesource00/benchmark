/**
 * Vendors the Astra engine into this benchmark as the shared host.
 *
 * The benchmark owns the copy. The sibling `astra/` development folder is read
 * as a source of bytes and is never written to, re-pinned, or mutated: this
 * script only ever reads from it and writes into `host/astra/`.
 *
 *   node scripts/vendor-astra.mjs [--check]
 *
 * `--check` exits non-zero when the vendored copy differs from the source.
 */
import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE = path.resolve(root, '..', 'astra');
export const TARGET = path.join(root, 'host', 'astra');

const COPY_DIRS = ['src', 'public'];
const COPY_FILES = ['index.html', 'package.json'];
const SKIP = new Set(['node_modules', '.git', 'dist', '.npm-cache', '.pnpm-store', 'artifacts', 'art', 'tests', '.gitignore']);

const hash = (buffer) => createHash('sha256').update(buffer).digest('hex');

async function walk(dir, base, out = []) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const entry of entries) {
    if (SKIP.has(entry.name)) continue;
    const absolute = path.join(dir, entry.name);
    const relative = path.join(base, entry.name);
    if (entry.isDirectory()) await walk(absolute, relative, out);
    else out.push({ absolute, relative });
  }
  return out;
}

async function collect() {
  const files = [];
  for (const dir of COPY_DIRS) files.push(...(await walk(path.join(SOURCE, dir), dir)));
  for (const file of COPY_FILES) {
    const absolute = path.join(SOURCE, file);
    try {
      await stat(absolute);
      files.push({ absolute, relative: file });
    } catch {
      /* optional file */
    }
  }
  return files;
}

async function main() {
  const checkOnly = process.argv.includes('--check');
  const files = await collect();
  if (!files.length) {
    console.error(`[vendor-astra] No source files found under ${SOURCE}. Is the astra checkout present?`);
    process.exit(1);
  }

  const manifest = [];
  let changed = 0;
  for (const file of files) {
    const bytes = await readFile(file.absolute);
    const target = path.join(TARGET, file.relative);
    manifest.push({ path: file.relative.split(path.sep).join('/'), bytes: bytes.length, sha256: hash(bytes) });
    if (checkOnly) continue;
    await mkdir(path.dirname(target), { recursive: true });
    let existing = null;
    try {
      existing = await readFile(target);
    } catch {
      /* not vendored yet */
    }
    if (!existing || hash(existing) !== hash(bytes)) {
      await writeFile(target, bytes);
      changed += 1;
    }
  }

  manifest.sort((a, b) => a.path.localeCompare(b.path));
  const manifestPath = path.join(TARGET, 'astra-manifest.json');

  if (checkOnly) {
    let current = null;
    try {
      current = JSON.parse(await readFile(manifestPath, 'utf8'));
    } catch {
      /* missing manifest counts as drift */
    }
    const drift = current?.files?.length !== manifest.length
      || manifest.some((entry, index) => current.files[index]?.sha256 !== entry.sha256);
    if (drift) {
      console.error(`[vendor-astra] Vendored copy under host/astra differs from ${SOURCE}. Run: npm run vendor:astra`);
      process.exit(1);
    }
    console.log(`[vendor-astra] host/astra matches ${SOURCE} (${manifest.length} files).`);
    return;
  }

  await rm(manifestPath, { force: true });
  await writeFile(manifestPath, `${JSON.stringify({
    source: '../astra',
    vendoredAt: new Date().toISOString(),
    note: 'Benchmark-owned copy. Generated by scripts/vendor-astra.mjs. Never edit by hand.',
    files: manifest
  }, null, 2)}\n`);

  console.log(`[vendor-astra] ${changed} file(s) written, ${manifest.length} total -> host/astra`);
}

const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invokedDirectly) main().catch((error) => {
  console.error(error);
  process.exit(1);
});
